export type PlcKey=keyof typeof plcDict.en;
// Lookup for code paths that rarely produce text (errors, diagnostics). Translators are cached per language.
const translators:Partial<Record<Lang,Translate<PlcKey>>>={};
export const plcTranslator=(lang?:Lang):Translate<PlcKey>=>{const l=langOf(lang);return translators[l]??=translator(plcDict,l);};
export const say=(lang:Lang|undefined,key:PlcKey,params?:Params)=>plcTranslator(lang)(key,params);
